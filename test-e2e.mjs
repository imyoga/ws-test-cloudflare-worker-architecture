// Automated E2E test for the WebSocket ping-pong exchange
async function runTest() {
  console.log("Testing HTTP GET UI...");
  const httpRes = await fetch("http://127.0.0.1:8787/");
  if (httpRes.status !== 200) {
    throw new Error(`HTTP GET failed with status ${httpRes.status}`);
  }
  const html = await httpRes.text();
  if (!html.includes("Cloudflare Worker WSS Ping-Pong")) {
    throw new Error("HTML does not contain expected UI title");
  }
  console.log("✓ HTTP GET successfully served the UI.");

  console.log("Testing WebSocket exchange at ws://127.0.0.1:8787/ws ...");
  
  return new Promise((resolve, reject) => {
    const ws = new WebSocket("ws://127.0.0.1:8787/ws");
    let rounds = 0;
    const maxRounds = 4;
    let baseString = "";

    const timeout = setTimeout(() => {
      ws.close();
      reject(new Error("Test timed out waiting for WS rounds"));
    }, 10000);

    ws.onopen = () => {
      console.log("✓ WebSocket connection opened successfully.");
    };

    ws.onmessage = (event) => {
      const msg = event.data;
      console.log(`[Round ${rounds}] Received from Server:`, msg);

      // Verify format: should match "<base> | TS: <iso-timestamp>"
      const match = msg.match(/^(.+?)\s*\|\s*TS:\s*(\S+)$/);
      if (!match) {
        clearTimeout(timeout);
        ws.close();
        return reject(new Error(`Received message doesn't match expected format: ${msg}`));
      }

      const receivedBase = match[1].trim();
      const serverTs = match[2].trim();

      if (!baseString) {
        baseString = receivedBase;
        console.log(`✓ Initial random string generated by server: "${baseString}"`);
      } else {
        if (receivedBase !== baseString) {
          clearTimeout(timeout);
          ws.close();
          return reject(new Error(`Base string changed unexpectedly! Expected "${baseString}", got "${receivedBase}"`));
        }
      }

      // Check ISO timestamp validity
      const parsedDate = new Date(serverTs);
      if (isNaN(parsedDate.getTime())) {
        clearTimeout(timeout);
        ws.close();
        return reject(new Error(`Invalid timestamp received: ${serverTs}`));
      }

      rounds++;
      if (rounds >= maxRounds) {
        clearTimeout(timeout);
        console.log(`✓ Successfully completed ${rounds} ping-pong timestamp cycles!`);
        ws.close();
        return resolve();
      }

      // Simulate UI: wait 1 second (or 300ms for fast test), strip old TS, append new client TS, send back
      setTimeout(() => {
        const clientTs = new Date().toISOString();
        const outgoing = `${baseString} | TS: ${clientTs}`;
        console.log(`[Round ${rounds}] Client sending back:`, outgoing);
        ws.send(outgoing);
      }, 500);
    };

    ws.onerror = (err) => {
      clearTimeout(timeout);
      reject(err);
    };

    ws.onclose = (event) => {
      console.log(`WebSocket closed (code: ${event.code})`);
    };
  });
}

runTest()
  .then(() => {
    console.log("=== ALL TESTS PASSED SUCCESSFULLY ===");
    process.exit(0);
  })
  .catch((err) => {
    console.error("Test failed:", err);
    process.exit(1);
  });
